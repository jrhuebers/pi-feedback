import { randomUUID } from "node:crypto";
import { constants } from "node:fs";
import { lstat, mkdir, open, readdir, rename, rmdir, unlink } from "node:fs/promises";
import { join } from "node:path";
import { setTimeout as delay } from "node:timers/promises";

export const STATUSES = ["inbox", "planned", "done"] as const;
export type Status = (typeof STATUSES)[number];
export interface Origin {
  profile: string;
  cluster?: string;
  cwd: string;
  sessionId: string;
  entryId?: string;
  model?: string;
  piVersion: string;
}
export interface Note {
  version: 1;
  id: string;
  status: Status;
  created: string;
  updated: string;
  origin: Origin;
  text: string;
}
export interface Snapshot { notes: Note[]; warnings: string[] }
const ID = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
const PREFIX = "<!-- pi-feedback ";
export const MAX_TEXT = 100_000;

export function isStatus(value: unknown): value is Status {
  return STATUSES.includes(value as Status);
}
export function cleanText(text: string): string {
  const result = text.replace(/\r\n?/g, "\n").trim();
  if (!result) throw new Error("Feedback cannot be empty.");
  if (result.length > MAX_TEXT) throw new Error(`Feedback exceeds ${MAX_TEXT} characters.`);
  return result;
}
export function title(note: Note): string { return note.text.split("\n")[0].replace(/^#+\s*/, ""); }
// Strip terminal control characters, including OSC/CSI initiators. Never render raw note text as ANSI.
export function plain(text: string): string {
  return text.replace(/[\u0000-\u0008\u000b-\u001f\u007f-\u009f]/g, "");
}
function encode(note: Note): string {
  const { text, ...metadata } = note;
  return `${PREFIX}${JSON.stringify(metadata).replaceAll("-->", "--\\u003e")} -->\n\n${text}\n`;
}
function decode(source: string, id: string): Note {
  const end = source.indexOf(" -->\n");
  if (!source.startsWith(PREFIX) || end < 0) throw new Error("Missing feedback metadata");
  const data = JSON.parse(source.slice(PREFIX.length, end));
  const origin = data?.origin;
  if (data?.version !== 1 || data.id !== id || !isStatus(data.status)
    || typeof data.created !== "string" || !Number.isFinite(Date.parse(data.created))
    || typeof data.updated !== "string" || !Number.isFinite(Date.parse(data.updated))
    || !origin || typeof origin.profile !== "string" || typeof origin.cwd !== "string"
    || typeof origin.sessionId !== "string" || typeof origin.piVersion !== "string"
    || [origin.cluster, origin.entryId, origin.model].some((value) => value !== undefined && typeof value !== "string")) {
    throw new Error("Invalid feedback metadata");
  }
  return { version: 1, id, status: data.status, created: data.created, updated: data.updated,
    origin, text: cleanText(source.slice(end + 5)) };
}
async function privateDirectory(path: string): Promise<void> {
  await mkdir(path, { recursive: true, mode: 0o700 });
  const info = await lstat(path);
  if (!info.isDirectory() || info.isSymbolicLink()) throw new Error(`Not an owned directory: ${path}`);
}
async function readRegular(path: string): Promise<string> {
  const file = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  try {
    const info = await file.stat();
    if (!info.isFile() || info.size > 1_000_000) throw new Error("Not a regular feedback file, or exceeds 1 MB");
    return await file.readFile("utf8");
  } finally { await file.close(); }
}
async function atomicWrite(path: string, text: string): Promise<void> {
  const temporary = `${path}.${randomUUID()}.tmp`;
  try {
    const file = await open(temporary, "wx", 0o600);
    try { await file.writeFile(text, "utf8"); await file.sync(); } finally { await file.close(); }
    await rename(temporary, path);
  } finally { await unlink(temporary).catch((error) => { if (error.code !== "ENOENT") throw error; }); }
}
function mdCell(text: string): string {
  return plain(text).replace(/[\r\n]/g, " ").replaceAll("&", "&amp;").replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;").replaceAll("|", "&#124;").replace(/([\\`*_[\]])/g, "\\$1");
}
export function markdownBoard(snapshot: Snapshot): string {
  const lines = ["# Feedback board", "", "Generated by pi-feedback. Notes in `items/` are the source of truth; do not edit this board.", ""];
  for (const status of STATUSES) {
    const notes = snapshot.notes.filter((note) => note.status === status);
    lines.push(`## ${status} (${notes.length})`, "", "| Feedback | Profile | Created |", "| --- | --- | --- |");
    for (const note of notes) lines.push(`| [${mdCell(title(note))}](items/${note.id}.md) | ${mdCell(note.origin.profile)} | ${note.created.slice(0, 10)} |`);
    lines.push("");
  }
  if (snapshot.warnings.length) lines.push("## Warnings", "", ...snapshot.warnings.map((warning) => `- ${mdCell(warning)}`), "");
  return lines.join("\n");
}

export class FeedbackStore {
  constructor(readonly root: string) {}
  path(id: string): string {
    if (!ID.test(id)) throw new Error("Invalid feedback ID");
    return join(this.root, "items", `${id}.md`);
  }
  private async locked<T>(action: () => Promise<T>): Promise<T> {
    await privateDirectory(this.root);
    await privateDirectory(join(this.root, "items"));
    const lock = join(this.root, ".lock");
    let acquired = false;
    for (let attempt = 0; attempt < 80; attempt++) {
      try { await mkdir(lock, { mode: 0o700 }); acquired = true; break; }
      catch (error) { if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error; }
      await delay(25);
    }
    if (!acquired) throw new Error(`Feedback store busy: ${lock}. Retry; if Pi crashed, remove this empty lock directory only after checking no writer is active.`);
    try { return await action(); } finally { await rmdir(lock); }
  }
  async list(): Promise<Snapshot> {
    let entries;
    try {
      const info = await lstat(this.root);
      if (!info.isDirectory() || info.isSymbolicLink()) throw new Error("Feedback root must be a directory, not a symlink");
      const items = join(this.root, "items");
      const itemInfo = await lstat(items);
      if (!itemInfo.isDirectory() || itemInfo.isSymbolicLink()) throw new Error("Feedback items must be a directory, not a symlink");
      entries = await readdir(items, { withFileTypes: true });
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return { notes: [], warnings: [] };
      throw error;
    }
    const notes: Note[] = [], warnings: string[] = [];
    for (const entry of entries) {
      if (!entry.name.endsWith(".md")) continue;
      const id = entry.name.slice(0, -3);
      try {
        if (!ID.test(id) || !entry.isFile()) throw new Error("Unexpected filename or file type");
        notes.push(decode(await readRegular(this.path(id)), id));
      } catch (error) { warnings.push(`${entry.name}: ${(error as Error).message}`); }
    }
    notes.sort((a, b) => b.created.localeCompare(a.created) || a.id.localeCompare(b.id));
    return { notes, warnings };
  }
  async add(text: string, origin: Origin): Promise<{ note: Note; boardWarning?: string }> {
    text = cleanText(text);
    return this.locked(async () => {
      const now = new Date().toISOString();
      const note: Note = { version: 1, id: randomUUID(), status: "inbox", created: now, updated: now, origin, text };
      await atomicWrite(this.path(note.id), encode(note));
      return { note, boardWarning: await this.updateBoard() };
    });
  }
  // Read the latest note inside the cross-process lock: moving never overwrites a concurrent text edit.
  async update(id: string, patch: { text?: string; status?: Status }, expectedUpdated?: string): Promise<{ note: Note; boardWarning?: string }> {
    this.path(id);
    if (patch.text !== undefined) patch = { ...patch, text: cleanText(patch.text) };
    if (patch.status !== undefined && !isStatus(patch.status)) throw new Error("Invalid status");
    return this.locked(async () => {
      const current = decode(await readRegular(this.path(id)), id);
      if (expectedUpdated !== undefined && current.updated !== expectedUpdated) {
        throw new Error("This note changed in another session. Your edit was not saved; reopen it and retry.");
      }
      const updated = new Date(Math.max(Date.now(), Date.parse(current.updated) + 1)).toISOString();
      const note = { ...current, ...patch, updated };
      await atomicWrite(this.path(id), encode(note));
      return { note, boardWarning: await this.updateBoard() };
    });
  }
  private async updateBoard(): Promise<string | undefined> {
    try { await atomicWrite(join(this.root, "BOARD.md"), markdownBoard(await this.list())); }
    catch (error) { return `Note saved, but BOARD.md could not be refreshed: ${(error as Error).message}`; }
  }
  async refresh(): Promise<Snapshot> {
    return this.locked(async () => {
      const snapshot = await this.list();
      await atomicWrite(join(this.root, "BOARD.md"), markdownBoard(snapshot));
      return snapshot;
    });
  }
}
